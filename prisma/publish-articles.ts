async function main() {
  console.log('Publishing full real articles to database...')

  for (const item of articles) {
    const existing = await prisma.post.findUnique({ where: { slug: item.slug } })
    if (!existing) {
      await prisma.post.create({
        data: {
          slug: item.slug,
          title: item.title,
          summary: item.summary,
          content: item.content,
          category: item.category,
          published: true,
        },
      })
      console.log(`+ Published article: ${item.title}`)
    } else {
      console.log(`- Article exists: ${item.title}`)
    }
  }

  console.log('All real articles published successfully.')
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
